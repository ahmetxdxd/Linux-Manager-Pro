# Records and rebuild tracking
# --------------------------------------------------------------------------- #

def registry_path() -> Path:
    return data_dir() / "builds.json"


def load_records() -> list[BuildRecord]:
    out = []
    for item in load_json(registry_path(), []):
        try:
            out.append(BuildRecord(**item))
        except TypeError:
            continue
    return out


def save_record(job: BuildJob, opts: BuildOptions) -> BuildRecord | None:
    version = pacman.installed_versions().get(job.name, "")
    if not version:
        return None
    rec = BuildRecord(name=job.name, source=job.source, target=job.target, built_version=version,
                      options=opts.summary(), date=datetime.now().strftime("%Y-%m-%d %H:%M"),
                      pkgbase=job.pkgbase)
    records = [r for r in load_records() if r.name != rec.name] + [rec]
    save_json(registry_path(), [asdict(r) for r in records])
    return rec


def forget_record(name: str) -> None:
    save_json(registry_path(), [asdict(r) for r in load_records() if r.name != name])


@dataclass
class RecordStatus:
    record: BuildRecord
    installed: str
    latest: str
    state: str          # ok / replaced / outdated / removed
    label: str


def record_statuses(check_aur: bool = True) -> list[RecordStatus]:
    records = load_records()
    if not records:
        return []
    installed = pacman.installed_versions()
    repo_info = pacman.sync_info([r.name for r in records if r.source == "repo"])
    present = [r.name for r in records if r.name in installed]
    packagers: dict[str, str] = {}
    if present:
        qi = run(["pacman", "-Qi", *present])
        packagers = {p.name: p.packager for p in pacman.parse_info(qi.out)}
    out = []
    for r in records:
        inst = installed.get(r.name, "")
        latest = ""
        if r.source == "repo" and r.name in repo_info:
            latest = repo_info[r.name].version
        elif r.source == "aur" and check_aur:
            info = aur_info(r.name)
            latest = info.get("Version", "") if info else ""
        if not inst:
            state, label = "removed", tr("Removed")
        elif packagers.get(r.name, PACKAGER) != PACKAGER:
            state, label = "replaced", tr("Replaced by the repo version, rebuild it")
        elif latest and pacman.vercmp(latest, inst) > 0:
            state, label = "outdated", tr("New version available: {v}").format(v=latest)
        else:
            state, label = "ok", tr("Up to date (local build)")
        out.append(RecordStatus(r, inst, latest, state, label))
    return out
