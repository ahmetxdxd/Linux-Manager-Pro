def gitlab_project_name(pkgbase: str) -> str:
    """devtools' gitlab path conversion (e.g. 'gtk2+extra' → 'gtk2-extra', 'tree' → 'unix-tree')."""
    name = re.sub(r"([a-zA-Z0-9]+)\+([a-zA-Z]+)", r"\1-\2", pkgbase)
    name = name.replace("+", "plus")
    name = re.sub(r"[^a-zA-Z0-9_\-.]", "-", name)
    name = re.sub(r"[_\-]{2,}", "-", name)
    return "unix-tree" if name == "tree" else name


def _http_json(url: str, timeout: float = 10) -> dict:
    req = urllib.request.Request(url, headers={"User-Agent": "linux-manager-pro"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def repo_pkgbase(name: str) -> str:
    try:
        data = _http_json("https://archlinux.org/packages/search/json/?name=" +
                          urllib.parse.quote(name))
        for r in data.get("results", []):
            if r.get("pkgname") == name:
                return r.get("pkgbase") or name
    except (OSError, ValueError):
        pass
    return name


def aur_info(name: str) -> dict | None:
    try:
        data = _http_json("https://aur.archlinux.org/rpc/v5/info?arg[]=" + urllib.parse.quote(name))
        results = data.get("results") or []
        return results[0] if results else None
    except (OSError, ValueError):
        return None


def version_tag(version: str) -> str:
    return version.replace(":", "-")


def git_pkgname(url: str) -> str:
    base = url.rstrip("/").split("/")[-1]
    if base.endswith(".git"):
        base = base[:-4]
    name = re.sub(r"[^a-z0-9@.+-]+", "-", base.lower()).strip("-.") or "project"
    return name if name.endswith("-git") else name + "-git"


def git_pkgbuild(url: str) -> str:
    pkgname = git_pkgname(url)
    provides = pkgname[:-4]
    return f"""# Generated by Linux Manager Pro: {url}
pkgname={pkgname}
pkgver=r0.0
pkgrel=1
pkgdesc="{tr("{name} (local build from git source)").format(name=provides)}"
arch=('x86_64' 'aarch64')
url={shlex.quote(url)}
license=('LicenseRef-unknown')
makedepends=('git')
provides=('{provides}')
conflicts=('{provides}')
source=("_src::git+{url}")
sha256sums=('SKIP')

pkgver() {{
  cd _src
  ( set -o pipefail
    git describe --long --tags --abbrev=7 2>/dev/null | sed 's/^v//;s/\\([^-]*-g\\)/r\\1/;s/-/./g' ||
    printf "r%s.%s" "$(git rev-list --count HEAD)" "$(git rev-parse --short=7 HEAD)" )
}}

_lmp_system() {{
  if   [[ -f CMakeLists.txt ]]; then echo cmake
  elif [[ -f meson.build ]]; then echo meson
  elif [[ -f Cargo.toml ]]; then echo cargo
  elif [[ -x configure ]]; then echo configure
  elif [[ -f configure.ac || -f autogen.sh ]]; then echo autotools
  elif [[ -f go.mod ]]; then echo go
  elif [[ -f pyproject.toml || -f setup.py ]]; then echo python
  elif [[ -f Makefile || -f makefile || -f GNUmakefile ]]; then echo make
  else echo unknown; fi
}}

build() {{
  cd _src
  local sys; sys=$(_lmp_system)
  echo "==> Derleme sistemi: $sys"
  case $sys in
    cmake) cmake -B build -S . -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX=/usr -Wno-dev
           cmake --build build ;;
    meson) meson setup build --prefix=/usr --libexecdir=lib --buildtype=release
           meson compile -C build ;;
    cargo) cargo build --release --locked || cargo build --release ;;
    autotools) if [[ -x autogen.sh ]]; then NOCONFIGURE=1 ./autogen.sh; else autoreconf -fi; fi
               ./configure --prefix=/usr; make ;;
    configure) ./configure --prefix=/usr; make ;;
    go) export CGO_CFLAGS="$CFLAGS" CGO_CXXFLAGS="$CXXFLAGS" CGO_LDFLAGS="$LDFLAGS"
        mkdir -p build; go build -trimpath -buildmode=pie -o build/ ./... ;;
    python) python -m build --wheel --no-isolation ;;
    make) make PREFIX=/usr ;;
    *) echo "{tr("ERROR: Build system not recognised. You need to write the PKGBUILD for this repository by hand.")}"
       return 1 ;;
  esac
}}

package() {{
  cd _src
  case $(_lmp_system) in
    cmake) DESTDIR="$pkgdir" cmake --install build ;;
    meson) meson install -C build --destdir "$pkgdir" ;;
    cargo) find target/release -maxdepth 1 -type f -executable \\
             -exec install -Dm755 -t "$pkgdir/usr/bin" {{}} + ;;
    autotools|configure) make DESTDIR="$pkgdir" install ;;
    go) find build -maxdepth 1 -type f -executable -exec install -Dm755 -t "$pkgdir/usr/bin" {{}} + ;;
    python) python -m installer --destdir="$pkgdir" dist/*.whl ;;
    make) make DESTDIR="$pkgdir" PREFIX=/usr install ;;
  esac
  for f in LICENSE* COPYING*; do
    [[ -f $f ]] && install -Dm644 "$f" "$pkgdir/usr/share/licenses/$pkgname/$f"
  done
  return 0
}}
"""


@dataclass
class BuildJob:
    source: str
    target: str
    name: str = ""                 # name of the package to install
    pkgbase: str = ""
    clone_url: str = ""
    tag: str = ""
    workdir: Path = field(default_factory=Path)
    notes: list[str] = field(default_factory=list)


def resolve(source: str, target: str) -> BuildJob:
    """Performs network queries; call it in the background. Raises ValueError on failure."""
    target = target.strip()
    job = BuildJob(source=source, target=target)
    if source == "repo":
        if not pacman.NAME_RE.match(target):
            raise ValueError(tr("Invalid package name."))
        info = pacman.sync_info([target]).get(target)
        if not info:
            raise ValueError(tr("'{target}' was not found in the sync repositories.").format(target=target))
        job.name = target
        job.pkgbase = repo_pkgbase(target)
        job.clone_url = ("https://gitlab.archlinux.org/archlinux/packaging/packages/"
                         f"{gitlab_project_name(job.pkgbase)}.git")
        job.tag = version_tag(info.version)
        if info.repository and info.repository not in ("core", "extra", "multilib",
                                                        "core-testing", "extra-testing"):
            job.notes.append(
                tr("The installed version comes from the '{repo}' repository; Arch's official "
                   "PKGBUILD will be built.").format(repo=info.repository))
    elif source == "aur":
        info = aur_info(target)
        if not info:
            raise ValueError(tr("'{target}' was not found in the AUR (or the AUR is unreachable).").format(target=target))
        job.name = info.get("Name", target)
        job.pkgbase = info.get("PackageBase", target)
        job.clone_url = f"https://aur.archlinux.org/{job.pkgbase}.git"
    elif source == "git":
        if not re.match(r"^(https://|git://|ssh://|git@)[^\s'\"]+$", target):
            raise ValueError(tr("Enter a valid git address (https://...)."))
        job.name = git_pkgname(target)
        job.pkgbase = job.name
        job.notes.append(tr("Build dependencies (cmake, meson, cargo…) cannot be detected "
                            "automatically; the build fails if some are missing."))
    else:
        raise ValueError(tr("Unknown source."))
    job.workdir = cache_dir() / "builds" / job.pkgbase
    return job


def build_script(job: BuildJob, opts: BuildOptions, conf: Path) -> str:
    q = shlex.quote
    work = q(str(job.workdir))
    lines = [
        "set -euo pipefail",
        'step() { printf \'@@LMP {"type":"status","message":"%s"}\\n\' "$1"; }',
        f"mkdir -p {work}",
        f"cd {work}",
        "rm -rf pkg-src",
    ]
    if job.source in ("repo", "aur"):
        lines += [
            f"step {q(tr('Downloading PKGBUILD'))}",
            f"git clone --quiet {q(job.clone_url)} pkg-src",
            "cd pkg-src",
        ]
        if job.tag:
            lines += [
                f"if git rev-parse -q --verify {q('refs/tags/' + job.tag)} >/dev/null; then",
                f"  git -c advice.detachedHead=false checkout --quiet {q(job.tag)}",
                f"  echo {q(tr('Tag: {tag}').format(tag=job.tag))}",
                "else",
                f"  echo {q(tr('No version tag found, using the latest PKGBUILD.'))}",
                "fi",
            ]
    else:
        lines += ["mkdir -p pkg-src", "cd pkg-src",
                  f"cat > PKGBUILD <<'LMP_PKGBUILD_EOF'\n{git_pkgbuild(job.target)}LMP_PKGBUILD_EOF"]
    if not opts.skip_pgp:
        lines += [
            f"step {q(tr('Checking PGP keys'))}",
            "for k in $(makepkg --printsrcinfo 2>/dev/null | sed -n 's/^\\s*validpgpkeys = //p'); do",
            "  gpg --list-keys \"$k\" >/dev/null 2>&1 || gpg --recv-keys \"$k\" || "
            "gpg --keyserver hkps://keyserver.ubuntu.com --recv-keys \"$k\" || true",
            "done",
        ]
    flags = ["-s", "-i", "-f", "--noconfirm"]
    if opts.skip_check:
        flags.append("--nocheck")
    if opts.skip_pgp:
        flags.append("--skippgpcheck")
    if opts.remove_makedeps:
        flags.append("-r")
    lines += [
        f"step {q(tr('Building (this can take a while)'))}",
        f"makepkg --config {q(str(conf))} {' '.join(flags)}",
        f"step {q(tr('Done'))}",
    ]
    return "\n".join(lines) + "\n"


