"""Gentoo-style local builds: compiles packages from source with flags tuned for this CPU.

Sources:
  * repo – PKGBUILD from the official Arch repos (gitlab.archlinux.org), at the installed version tag
  * aur  – the AUR
  * git  – any git repository; the build system (cmake/meson/cargo/autotools/make/go/
           python) is auto-detected inside the generated PKGBUILD at build time

Builds always run as the normal user (makepkg refuses to run as root). Dependency and
package installation go through the password dialog via makepkg's PACMAN_AUTH=(pkexec).
"""

from __future__ import annotations

import json
import os
import re
import shlex
import urllib.parse
import urllib.request
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path

from lmp.core import pacman
from lmp.core.util import cache_dir, data_dir, have, load_json, run, save_json
from lmp.i18n import tr, tr_noop

PACKAGER = "Linux Manager Pro (local build) <local@linux-manager-pro>"
SOURCES = {"repo": tr_noop("Official repo"), "aur": "AUR", "git": tr_noop("Git repository")}


@dataclass
class BuildOptions:
    march_native: bool = True
    opt_level: str = "O2"            # O2 / O3
    lto: bool = True
    ccache: bool = False
    skip_check: bool = True
    skip_pgp: bool = False
    no_debug: bool = True
    remove_makedeps: bool = False
    jobs: int = 0                    # 0 → number of CPU cores

    def summary(self) -> str:
        parts = []
        if self.march_native:
            parts.append("-march=native")
        parts.append(f"-{self.opt_level}")
        if self.lto:
            parts.append("LTO")
        if self.ccache:
            parts.append("ccache")
        return " ".join(parts)


@dataclass
class BuildRecord:
    name: str
    source: str
    target: str                       # package name or git URL
    built_version: str
    options: str
    date: str
    pkgbase: str = ""


# --------------------------------------------------------------------------- #
# Config generation
# --------------------------------------------------------------------------- #

def makepkg_conf_text(opts: BuildOptions) -> str:
    jobs = opts.jobs or os.cpu_count() or 2
    lines = [
        "# Generated by Linux Manager Pro. Overrides the system makepkg.conf.",
        "source /etc/makepkg.conf",
        "for _lmp_f in /etc/makepkg.conf.d/*.conf; do [[ -r $_lmp_f ]] && source \"$_lmp_f\"; done",
        "unset _lmp_f",
        # strip -march/-mtune/-O values from the existing flags, keep the rest (such as
        # hardening flags) untouched
        "_lmp_strip() { local o=() x; for x in $1; do case $x in -march=*|-mtune=*|-O?|-O) ;; "
        "*) o+=(\"$x\");; esac; done; printf '%s' \"${o[*]}\"; }",
    ]
    arch = "-march=native -mtune=native " if opts.march_native else ""
    lines += [
        f'CFLAGS="{arch}-{opts.opt_level} $(_lmp_strip "$CFLAGS")"',
        f'CXXFLAGS="{arch}-{opts.opt_level} $(_lmp_strip "$CXXFLAGS")"',
    ]
    rust_opt = "3" if opts.opt_level == "O3" else "2"
    rust_cpu = "-C target-cpu=native " if opts.march_native else ""
    # for rustc the last occurrence of a -C option wins, so ours are appended at the end
    lines += [
        f'RUSTFLAGS="${{RUSTFLAGS:-}} {rust_cpu}-C opt-level={rust_opt}"',
        f'MAKEFLAGS="-j{jobs}"',
        f"NINJAFLAGS=\"-j{jobs}\"",
        "unset -f _lmp_strip",
        "PACMAN_AUTH=(pkexec)",
        f'PACKAGER="{PACKAGER}"',
        "_lmp_opt() { local want=$1 o=() x; for x in \"${OPTIONS[@]}\"; do "
        "[[ $x == \"$want\" || $x == \"!$want\" ]] || o+=(\"$x\"); done; OPTIONS=(\"${o[@]}\" \"$2\"); }",
        f"_lmp_opt lto {'lto' if opts.lto else '!lto'}",
        f"_lmp_opt ccache {'ccache' if opts.ccache else '!ccache'}",
        f"_lmp_opt debug {'!debug' if opts.no_debug else 'debug'}",
        "unset -f _lmp_opt",
    ]
    return "\n".join(lines) + "\n"


def write_conf(opts: BuildOptions) -> Path:
    path = cache_dir() / "makepkg.conf"
    path.write_text(makepkg_conf_text(opts), encoding="utf-8")
    return path


def effective_flags(opts: BuildOptions) -> str:
    """Preview: the value that results from applying these settings on top of the system CFLAGS."""
    conf = write_conf(opts)
    res = run(["bash", "-c", f'source {shlex.quote(str(conf))} 2>/dev/null; '
                             'printf "CFLAGS=%s\\nRUSTFLAGS=%s\\nMAKEFLAGS=%s\\nOPTIONS=%s\\n" '
                             '"$CFLAGS" "$RUSTFLAGS" "$MAKEFLAGS" "${OPTIONS[*]}"'], timeout=10)
    return res.out.strip()


def native_cpu() -> tuple[str, str]:
    """(CPU model, the architecture gcc picks for -march=native)"""
    model = ""
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                model = line.split(":", 1)[1].strip()
                break
    except OSError:
        pass
    march = ""
    if have("gcc"):
        res = run(["gcc", "-march=native", "-Q", "--help=target"], timeout=15)
        m = re.search(r"^\s*-march=\s+(\S+)", res.out, re.M)
        if m:
            march = m.group(1)
    return model, march


